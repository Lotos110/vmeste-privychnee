"""Запуск приложения как веб-страницы для проверки с телефона в той же Wi-Fi сети.

Python-код приложения выполняется на компьютере, а телефон только показывает интерфейс
в браузере. Поэтому адрес сервера в приложении остаётся http://127.0.0.1:8000.

Запуск (из папки mobile/, с включённым окружением):  python run_web.py
Затем на телефоне откройте  http://<IP компьютера>:8550
"""

import flet as ft

from main import main

PORT = 8550

if __name__ == "__main__":
    ft.app(target=main, view=ft.AppView.WEB_BROWSER, host="0.0.0.0", port=PORT)
